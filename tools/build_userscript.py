#!/usr/bin/env python3
"""
Builds `legium.user.js` from the extension's own files.

The exporter lives once, in `extension/notebook.js`. The extension loads it as a
content script; this wraps the same file for Tampermonkey, Violentmonkey and
the Userscripts app, which run in browsers the extension doesn't. Name, version,
description and the pages it runs on come from `extension/manifest.json`, so the
two can't drift apart.

    python3 tools/build_userscript.py           write the userscript
    python3 tools/build_userscript.py --check   fail if it is out of date

Run it after changing anything under `extension/`, and commit the result:
Tampermonkey installs and updates from the committed file.
"""

import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "extension", "manifest.json")
CORE = os.path.join(ROOT, "extension", "notebook.js")
OUT = os.path.join(ROOT, "legium.user.js")

# Saves through a link on the page: all a userscript with no grants can do.
GLUE = """
// ---------------------------------------------------------------- userscript

(function () {
    'use strict';

    globalThis.legiumExport.start({
        save({ filename, type, data }) {
            const url = URL.createObjectURL(new Blob([data], { type }));
            const anchor = document.createElement('a');
            anchor.href = url;
            anchor.download = filename;
            document.body.appendChild(anchor);
            anchor.click();
            anchor.remove();
            setTimeout(() => URL.revokeObjectURL(url), 10000);
            return Promise.resolve();
        },
    });
})();
"""


def build():
    with open(MANIFEST, encoding="utf-8") as fh:
        manifest = json.load(fh)
    with open(CORE, encoding="utf-8") as fh:
        core = fh.read()

    fields = [
        ("name", manifest["name"]),
        ("namespace", "dev.hronir.legium"),
        ("version", manifest["version"]),
        ("description", manifest["description"]),
        ("author", "Hronir LLC"),
    ]
    for script in manifest["content_scripts"]:
        fields += [("match", m) for m in script["matches"]]
    fields += [("grant", "none"), ("run-at", "document-idle")]

    width = max(len(k) for k, _ in fields) + 2
    header = ["// ==UserScript=="]
    header += [f"// @{k.ljust(width - 1)}{v}" for k, v in fields]
    header += [
        "// ==/UserScript==",
        "",
        "// Generated by tools/build_userscript.py from extension/notebook.js.",
        "// Edit that file, not this one.",
        "",
    ]
    return "\n".join(header) + core.rstrip("\n") + "\n" + GLUE


def main():
    built = build()
    if sys.argv[1:] == ["--check"]:
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() != built:
                sys.exit("legium.user.js is out of date: run tools/build_userscript.py")
        print("userscript is up to date")
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(built)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
